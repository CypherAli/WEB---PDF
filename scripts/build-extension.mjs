function crc32(buffer) {
  let crc=0xffffffff;
  for(const byte of buffer) {crc^=byte;for(let i=0;i<8;i++) crc=(crc>>>1)^((crc&1)?0xedb88320:0);}
  return (crc^0xffffffff)>>>0;
}
function pngChunk(type,data) {
  const label=Buffer.from(type),size=Buffer.alloc(4),crc=Buffer.alloc(4);
  size.writeUInt32BE(data.length);crc.writeUInt32BE(crc32(Buffer.concat([label,data])));
  return Buffer.concat([size,label,data,crc]);
}
function icon(size) {
  const raw=Buffer.alloc((size*4+1)*size);
  const rounded=(x,y,left,top,right,bottom,r)=>{
    if(x<left || x>right || y<top || y>bottom) return false;
    const dx=Math.max(left+r-x,0,x-(right-r)),dy=Math.max(top+r-y,0,y-(bottom-r));
    return dx*dx+dy*dy<=r*r;
  };
  for(let y=0;y<size;y++) for(let x=0;x<size;x++) {
    const rgb=[0,0,0];let alpha=0;
    for(let sy=0;sy<4;sy++) for(let sx=0;sx<4;sx++) {
      const px=(x+(sx+.5)/4)/size,py=(y+(sy+.5)/4)/size;
      if(!rounded(px,py,.015,.015,.985,.985,.2)) continue;
      let color=[28,98,216];
      if(rounded(px,py,.28,.18,.73,.83,.035)) color=[255,255,255];
      if(px>.57 && py<.34 && px-.57>py-.18) color=[180,210,253];
      if(px>.36 && px<.63 && ((py>.43&&py<.47)||(py>.55&&py<.59)||(py>.67&&py<.71))) color=[28,98,216];
      alpha++;for(let c=0;c<3;c++) rgb[c]+=color[c];
    }
    const off=y*(size*4+1)+1+x*4;
    for(let c=0;c<3;c++) raw[off+c]=alpha?Math.round(rgb[c]/alpha):0;
    raw[off+3]=Math.round(alpha/16*255);
  }
  const header=Buffer.alloc(13);header.writeUInt32BE(size,0);header.writeUInt32BE(size,4);header[8]=8;header[9]=6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),pngChunk('IHDR',header),pngChunk('IDAT',deflateSync(raw)),pngChunk('IEND',Buffer.alloc(0))]);
}
